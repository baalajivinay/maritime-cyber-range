"""Render a ScenarioResult as JSON (machine) and Markdown (the evaluator-facing
T&E artifact, with standards mapping)."""
import json
from . import standards

_SEV_LABEL = {"none": "NO IMPACT", "low": "LOW", "medium": "MEDIUM",
              "high": "HIGH", "critical": "CRITICAL"}


def to_dict(result):
    return {
        "scenario": result.scenario_name,
        "description": result.description,
        "target": result.target,
        "domain": result.domain,
        "executor": result.executor,
        "overall_severity": result.overall_severity,
        "telemetry_summary": result.telemetry_summary,
        "attacks_run": result.attacks_run,
        "consequences": [
            {**r.as_dict(),
             "standards": [{"standard": s, "control": c}
                           for (s, c) in standards.controls_for(r.type)]}
            for r in result.results
        ],
    }


def to_json(result, indent=2):
    return json.dumps(to_dict(result), indent=indent)


def to_markdown(result):
    L = []
    L.append(f"# Scenario T&E report: {result.scenario_name}")
    if result.description:
        L.append(f"\n{result.description}")
    L.append(f"\n- **Target:** `{result.target}`  ·  **Domain:** {result.domain}"
             f"  ·  **Executor:** {result.executor}")
    ts = result.telemetry_summary
    L.append(f"- **Run:** {ts.get('samples', 0)} samples / {ts.get('duration_s', 0)} s, "
             f"peak true-vs-believed divergence {ts.get('peak_divergence_m', 0)} m")
    L.append(f"\n## Mission-impact verdict: **{_SEV_LABEL.get(result.overall_severity, result.overall_severity.upper())}**")

    L.append("\n## Consequences")
    L.append("\n| Consequence | Result | Metric | At (s) | Severity |")
    L.append("|---|---|---|---|---|")
    for r in result.results:
        L.append(f"| {r.type} | {'⚠️ TRIGGERED' if r.triggered else 'ok'} | "
                 f"{r.metric if r.metric >= 0 else '—'} | {r.at_s if r.at_s >= 0 else '—'} | "
                 f"{r.severity} |")

    triggered = [r for r in result.results if r.triggered]
    if triggered:
        L.append("\n## Findings & standards mapping")
        for r in triggered:
            L.append(f"\n**{r.type}** ({r.severity}) — {r.detail}")
            ctrls = standards.controls_for(r.type)
            if ctrls:
                for s, c in ctrls:
                    L.append(f"  - `{s}` — {c}")

    if result.attacks_run:
        L.append("\n## Attacks exercised")
        for a in result.attacks_run:
            L.append(f"- t+{a['at_s']:.0f}s `{a['action']}` {a['params'] or ''}")

    L.append("\n---\n*Generated by the scale-up scenario engine (prototype). "
             "Standards references name the controlling documents; clause-level "
             "mapping is a Phase-II refinement with the controlling authority.*")
    return "\n".join(L)
